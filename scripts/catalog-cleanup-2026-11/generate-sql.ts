/**
 * Generates drizzle/0016_catalog_cleanup.sql and drizzle/0016_catalog_cleanup.down.sql
 * from ./mapping.ts. Run: npx tsx scripts/catalog-cleanup-2026-11/generate-sql.ts
 */
import { writeFileSync } from "node:fs";
import path from "node:path";

import { CATEGORIES, PRODUCTS } from "./mapping";

const BACKUP_SUFFIX = "backup_20261113";
const root = process.cwd();

function q(value: string | null | undefined) {
  if (value === null || value === undefined) return "NULL";
  return `'${value.replace(/'/g, "''")}'`;
}

// --- validation -------------------------------------------------------------
const ids = new Set<string>();
const slugs = new Set<string>();
for (const product of PRODUCTS) {
  if (ids.has(product.id)) throw new Error(`Duplicate id ${product.id}`);
  if (slugs.has(product.slug)) throw new Error(`Duplicate slug ${product.slug}`);
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(product.slug)) throw new Error(`Bad slug ${product.slug}`);
  ids.add(product.id);
  slugs.add(product.slug);
}
const categoryBySlug = new Map(CATEGORIES.map((category) => [category.slug, category]));

// --- up ---------------------------------------------------------------------
const up: string[] = [
  "-- Catalog cleanup (2026-11-13). Generated by scripts/catalog-cleanup-2026-11/generate-sql.ts.",
  "-- Reverse with drizzle/0016_catalog_cleanup.down.sql (restores from the backup tables).",
  "BEGIN;",
  "",
  "-- 1. Backups (kept until dropped manually).",
  `CREATE TABLE IF NOT EXISTS products_${BACKUP_SUFFIX} AS TABLE products;`,
  `CREATE TABLE IF NOT EXISTS product_variants_${BACKUP_SUFFIX} AS TABLE product_variants;`,
  `CREATE TABLE IF NOT EXISTS categories_${BACKUP_SUFFIX} AS TABLE categories;`,
  "",
  "-- 2. Columns. The first eight exist in src/db/schema.ts but were missing from the live table,",
  "--    which made every Drizzle product query fail (column \"brand\" does not exist).",
  "ALTER TABLE products",
  "  ADD COLUMN IF NOT EXISTS brand text,",
  "  ADD COLUMN IF NOT EXISTS rating numeric,",
  "  ADD COLUMN IF NOT EXISTS created_order integer,",
  "  ADD COLUMN IF NOT EXISTS source_sheet text,",
  "  ADD COLUMN IF NOT EXISTS source_block text,",
  "  ADD COLUMN IF NOT EXISTS source_row text,",
  "  ADD COLUMN IF NOT EXISTS source_segment text,",
  "  ADD COLUMN IF NOT EXISTS migration_batch_id text,",
  "  ADD COLUMN IF NOT EXISTS slug_public text,",
  "  ADD COLUMN IF NOT EXISTS category_id text;",
  "ALTER TABLE categories",
  "  ADD COLUMN IF NOT EXISTS name_km text,",
  "  ADD COLUMN IF NOT EXISTS sort_order integer;",
  "",
  "-- 3. Categories: Lights, Fans, Cables, Solar, Accessories (existing rows keep their ids).",
];

for (const category of CATEGORIES) {
  if (category.oldSlug === null) {
    up.push(
      `INSERT INTO categories (id, name, slug, created_by_id, created_at, updated_at, name_km, sort_order)`,
      `SELECT ${q(`cat_${category.slug}`)}, ${q(category.name)}, ${q(category.slug)}, created_by_id, now(), now(), ${q(category.nameKm)}, ${category.sortOrder}`,
      `FROM categories WHERE slug IN ('lighting-accessary', 'lights') LIMIT 1`,
      `ON CONFLICT (id) DO NOTHING;`,
    );
  } else {
    up.push(
      `UPDATE categories SET slug = ${q(category.slug)}, name = ${q(category.name)}, name_km = ${q(category.nameKm)}, sort_order = ${category.sortOrder}, updated_at = now() WHERE slug = ${q(category.oldSlug)};`,
    );
  }
}

up.push("", "-- 4. Products: category, brand, distinguishing titles, public slugs.");
for (const product of PRODUCTS) {
  const category = categoryBySlug.get(product.category)!;
  const sets = [
    `category = ${q(category.slug)}`,
    `category_id = (SELECT id FROM categories WHERE slug = ${q(category.slug)})`,
    `category_label = ${q(category.name)}`,
    `category_label_km = ${q(category.nameKm)}`,
    `brand = ${q(product.brand)}`,
    `slug_public = ${q(product.slug)}`,
    ...(product.title ? [`title = ${q(product.title)}`] : []),
    "updated_at = now()",
  ];
  up.push(`UPDATE products SET ${sets.join(", ")} WHERE id = ${q(product.id)};`);
}

up.push(
  "",
  "-- 5. Listing price = cheapest active option, so price filters and sorting match the cards.",
  "UPDATE products p SET price = v.min_price, updated_at = now()",
  "FROM (",
  "  SELECT product_id, MIN(price) AS min_price FROM product_variants",
  "  WHERE is_active AND price IS NOT NULL GROUP BY product_id",
  ") v",
  "WHERE v.product_id = p.id AND p.price IS DISTINCT FROM v.min_price;",
  "",
  "-- 6. Constraints and indexes for the listing query.",
  "ALTER TABLE products DROP CONSTRAINT IF EXISTS products_category_id_fkey;",
  "ALTER TABLE products ADD CONSTRAINT products_category_id_fkey",
  "  FOREIGN KEY (category_id) REFERENCES categories(id) ON UPDATE CASCADE ON DELETE SET NULL;",
  "CREATE UNIQUE INDEX IF NOT EXISTS products_slug_public_key ON products (slug_public);",
  "CREATE INDEX IF NOT EXISTS products_active_category_price_idx ON products (is_active, category, price);",
  "CREATE INDEX IF NOT EXISTS products_active_brand_price_idx ON products (is_active, lower(brand), price);",
  "",
  "COMMIT;",
  "",
);

// --- down -------------------------------------------------------------------
const down = [
  "-- Reverses drizzle/0016_catalog_cleanup.sql using the backup tables it created.",
  "-- Keeps the nullable drift-fix columns (brand, rating, created_order, source_*, migration_batch_id)",
  "-- because src/db/schema.ts selects them; brand values are cleared.",
  "BEGIN;",
  "ALTER TABLE products DROP CONSTRAINT IF EXISTS products_category_id_fkey;",
  "DROP INDEX IF EXISTS products_slug_public_key;",
  "DROP INDEX IF EXISTS products_active_category_price_idx;",
  "DROP INDEX IF EXISTS products_active_brand_price_idx;",
  `UPDATE products p SET title = b.title, price = b.price, category = b.category,`,
  `  category_label = b.category_label, category_label_km = b.category_label_km, updated_at = b.updated_at`,
  `FROM products_${BACKUP_SUFFIX} b WHERE b.id = p.id;`,
  "UPDATE products SET brand = NULL;",
  "ALTER TABLE products DROP COLUMN IF EXISTS slug_public, DROP COLUMN IF EXISTS category_id;",
  `UPDATE categories c SET name = b.name, slug = b.slug, updated_at = b.updated_at`,
  `FROM categories_${BACKUP_SUFFIX} b WHERE b.id = c.id;`,
  `DELETE FROM categories WHERE id NOT IN (SELECT id FROM categories_${BACKUP_SUFFIX});`,
  "ALTER TABLE categories DROP COLUMN IF EXISTS name_km, DROP COLUMN IF EXISTS sort_order;",
  "COMMIT;",
  "",
  `-- After confirming, drop the backups: DROP TABLE products_${BACKUP_SUFFIX}, product_variants_${BACKUP_SUFFIX}, categories_${BACKUP_SUFFIX};`,
  "",
];

writeFileSync(path.join(root, "drizzle/0016_catalog_cleanup.sql"), up.join("\n"));
writeFileSync(path.join(root, "drizzle/0016_catalog_cleanup.down.sql"), down.join("\n"));
console.log(`Wrote migration for ${PRODUCTS.length} products, ${CATEGORIES.length} categories.`);
